import { Table, Relationship, BackendConfig, VirtualFile, DbType } from '../../types/index';
import { toPascalCase } from './common';

// 1. Prisma Schema Generator
export const generatePrismaSchema = (tables: Table[], rawRelationships: Relationship[], config: BackendConfig): string => {
  const relationships = rawRelationships.filter((rel, index, self) =>
    index === self.findIndex((r) =>
      r.fromTableId === rel.fromTableId &&
      r.fromFieldId === rel.fromFieldId &&
      r.toTableId === rel.toTableId &&
      r.toFieldId === rel.toFieldId
    )
  );

  let provider = 'postgresql';
  if (config.dbType === DbType.MySQL) provider = 'mysql';
  else if (config.dbType === DbType.SQLite) provider = 'sqlite';
  else if (config.dbType === DbType.SQL) provider = 'sqlserver';

  let code = `// Prisma Schema for ${config.projectName}\n`;
  code += `// Generated by SQL Editor - ${new Date().toLocaleDateString()}\n\n`;

  code += `datasource db {\n`;
  code += `  provider = "${provider}"\n`;
  code += `  url      = env("DATABASE_URL")\n`;
  code += `}\n\n`;

  code += `generator client {\n`;
  code += `  provider = "prisma-client-js"\n`;
  code += `}\n\n`;

  tables.forEach(table => {
    const modelName = toPascalCase(table.name);
    code += `model ${modelName} {\n`;

    // Normal Fields
    table.fields.forEach(field => {
      let type = 'String';
      const fTypeUpper = (field.type || 'VARCHAR').toUpperCase();

      if (fTypeUpper.includes('INT')) {
        type = 'Int';
      } else if (fTypeUpper === 'BOOLEAN' || fTypeUpper === 'BOOL') {
        type = 'Boolean';
      } else if (fTypeUpper.includes('DATE') || fTypeUpper.includes('TIME')) {
        type = 'DateTime';
      } else if (fTypeUpper.includes('DECIMAL') || fTypeUpper.includes('DOUBLE') || fTypeUpper.includes('FLOAT') || fTypeUpper.includes('NUMERIC')) {
        type = 'Float';
      }

      // SQLite mapping constraints
      if (provider === 'sqlite' && fTypeUpper === 'DATETIME') {
        type = 'DateTime';
      }

      let decorators = '';
      if (field.isPrimaryKey) {
        decorators += ' @id';
        if (field.isAutoIncrement) {
          decorators += ' @default(autoincrement())';
        }
      }

      if (field.defaultValue !== undefined && field.defaultValue !== '' && !field.isPrimaryKey) {
        const defVal = field.defaultValue;
        if (['Int', 'Float'].includes(type) && !isNaN(Number(defVal))) {
          decorators += ` @default(${defVal})`;
        } else if (type === 'Boolean') {
          decorators += ` @default(${defVal === 'true' || defVal === '1'})`;
        } else if (type === 'DateTime' && typeof defVal === 'string' && ['NOW', 'CURRENT_TIMESTAMP'].includes(defVal.toUpperCase())) {
          decorators += ' @default(now())';
        } else {
          decorators += ` @default("${defVal.replace(/"/g, '\\"')}")`;
        }
      }

      const isForeignKey = relationships.some(r => r.toTableId === table.id && r.toFieldId === field.id);
      
      // If field is used in relation directly, Prisma wants you to define it but also the virtual relation
      const isNullPart = field.allowNull ? '?' : '';
      code += `  ${field.name} ${type}${isNullPart}${decorators}\n`;
    });

    // Relations (Outgoing / Foreign Keys)
    relationships.forEach(rel => {
      if (rel.toTableId === table.id) { // This table has the FK
        const parentTable = tables.find(t => t.id === rel.fromTableId);
        const fkField = table.fields.find(f => f.id === rel.toFieldId);
        const parentField = parentTable?.fields.find(f => f.id === rel.fromFieldId);

        if (parentTable && fkField && parentField) {
          const relationName = toPascalCase(parentTable.name);
          const virtualPropName = relationName.toLowerCase();
          
          let relationDecorators = `@relation(fields: [${fkField.name}], references: [${parentField.name}]`;
          if (rel.onDelete && rel.onDelete !== 'NO ACTION') {
            const delAction = rel.onDelete === 'SET NULL' ? 'SetNull' : rel.onDelete === 'CASCADE' ? 'Cascade' : 'NoAction';
            relationDecorators += `, onDelete: ${delAction}`;
          }
          if (rel.onUpdate && rel.onUpdate !== 'NO ACTION') {
            const updAction = rel.onUpdate === 'SET NULL' ? 'SetNull' : rel.onUpdate === 'CASCADE' ? 'Cascade' : 'NoAction';
            relationDecorators += `, onUpdate: ${updAction}`;
          }
          relationDecorators += `)`;

          code += `  ${virtualPropName} ${relationName}${fkField.allowNull ? '?' : ''} ${relationDecorators}\n`;
        }
      }
    });

    // Back-relations (Incoming Keys / One-To-Many references)
    relationships.forEach(rel => {
      if (rel.fromTableId === table.id) { // Other tables reference this table
        const childTable = tables.find(t => t.id === rel.toTableId);
        const childField = childTable?.fields.find(f => f.id === rel.toFieldId);
        if (childTable && childField) {
          const relationName = toPascalCase(childTable.name);
          const virtualPropNameList = relationName.toLowerCase() + 's';
          code += `  ${virtualPropNameList} ${relationName}[]\n`;
        }
      }
    });

    // Indexes
    const specialFields = ['club_id', 'user_id', 'conversation_id', 'clubid', 'userid', 'conversationid'];
    const indexedFields: string[] = [];
    
    table.fields.forEach(field => {
        const isSpecial = specialFields.includes(field.name.toLowerCase()) || field.name.toLowerCase().endsWith('_id');
        const isFk = relationships.some(rel => rel.toTableId === table.id && rel.toFieldId === field.id);
        
        if ((field.isIndexed || isSpecial || isFk) && !field.isPrimaryKey) {
            indexedFields.push(field.name);
        }
    });

    if (indexedFields.length > 0) {
        indexedFields.forEach(f => {
            code += `  @@index([${f}])\n`;
        });
    }

    code += `}\n\n`;
  });

  return code;
};

// 2. Drizzle ORM Schema Generator
export const generateDrizzleSchema = (tables: Table[], rawRelationships: Relationship[], config: BackendConfig): string => {
  const relationships = rawRelationships.filter((rel, index, self) =>
    index === self.findIndex((r) =>
      r.fromTableId === rel.fromTableId &&
      r.fromFieldId === rel.fromFieldId &&
      r.toTableId === rel.toTableId &&
      r.toFieldId === rel.toFieldId
    )
  );

  let isPg = config.dbType === DbType.SQL || config.dbType === DbType.PostgreSQL || config.dbType === undefined;
  let isMySql = config.dbType === DbType.MySQL;
  let isSqlite = config.dbType === DbType.SQLite;

  let imports = `import { `;
  if (isMySql) {
    imports += `mysqlTable, varchar, integer, boolean, datetime, double, text, serial, index`;
  } else if (isSqlite) {
    imports += `sqliteTable, text, integer, real, numeric, index`;
  } else {
    imports += `pgTable, varchar, integer, boolean, timestamp, doublePrecision, text, serial, uuid, index`;
  }
  imports += ` } from 'drizzle-orm/`;
  imports += isMySql ? 'mysql-core' : isSqlite ? 'sqlite-core' : 'pg-core';
  imports += `';\n`;
  imports += `import { relations } from 'drizzle-orm';\n\n`;

  let code = `// Drizzle Schema for ${config.projectName}\n`;
  code += `// Generated by SQL Editor - ${new Date().toLocaleDateString()}\n\n`;
  code += imports + `\n`;

  // Define tables
  tables.forEach(table => {
    const tableNameConst = `${table.name.toLowerCase()}Table`;
    const tableNameDb = table.name.toLowerCase();
    const tableFn = isMySql ? 'mysqlTable' : isSqlite ? 'sqliteTable' : 'pgTable';

    code += `export const ${tableNameConst} = ${tableFn}('${tableNameDb}', {\n`;

    table.fields.forEach(field => {
      let colDef = '';
      const fTypeUpper = (field.type || 'VARCHAR').toUpperCase();

      if (field.isPrimaryKey && field.isAutoIncrement) {
        if (isPg) colDef = `serial('${field.name}').primaryKey()`;
        else if (isMySql) colDef = `serial('${field.name}').primaryKey()`;
        else colDef = `integer('${field.name}').primaryKey({ autoIncrement: true })`;
      } else {
        if (fTypeUpper.includes('INT')) {
          colDef = `integer('${field.name}')`;
        } else if (fTypeUpper === 'BOOLEAN' || fTypeUpper === 'BOOL') {
          colDef = isSqlite ? `integer('${field.name}', { mode: 'boolean' })` : `boolean('${field.name}')`;
        } else if (fTypeUpper.includes('DATE') || fTypeUpper.includes('TIME')) {
          if (isMySql) colDef = `datetime('${field.name}')`;
          else if (isSqlite) colDef = `text('${field.name}')`;
          else colDef = `timestamp('${field.name}')`;
        } else if (fTypeUpper.includes('DECIMAL') || fTypeUpper.includes('DOUBLE') || fTypeUpper.includes('FLOAT') || fTypeUpper.includes('NUMERIC')) {
          if (isMySql) colDef = `double('${field.name}')`;
          else if (isSqlite) colDef = `real('${field.name}')`;
          else colDef = `doublePrecision('${field.name}')`;
        } else {
          // Varchar / Text
          const len = field.length || 255;
          colDef = `varchar('${field.name}', { length: ${len} })`;
        }

        if (field.isPrimaryKey) {
          colDef += `.primaryKey()`;
        }
        if (!field.allowNull && !field.isPrimaryKey) {
          colDef += `.notNull()`;
        }
        if (field.defaultValue !== undefined && field.defaultValue !== '' && !field.isPrimaryKey) {
          const defVal = field.defaultValue;
          if (!isNaN(Number(defVal))) {
            colDef += `.default(${defVal})`;
          } else if (defVal === 'true' || defVal === 'false') {
            colDef += `.default(${defVal})`;
          } else if (defVal && typeof defVal === 'string' && ['NOW', 'CURRENT_TIMESTAMP'].includes(defVal.toUpperCase())) {
            colDef += `.defaultNow()`;
          } else {
            colDef += `.default('${defVal.replace(/'/g, "\\'")}')`;
          }
        }
      }

      code += `  ${field.name}: ${colDef},\n`;
    });

    // Drizzle Indexes
    const specialFields = ['club_id', 'user_id', 'conversation_id', 'clubid', 'userid', 'conversationid'];
    const indexedFields: string[] = [];
    table.fields.forEach(field => {
        const isSpecial = specialFields.includes(field.name.toLowerCase()) || field.name.toLowerCase().endsWith('_id');
        const isFk = relationships.some(rel => rel.toTableId === table.id && rel.toFieldId === field.id);
        
        if ((field.isIndexed || isSpecial || isFk) && !field.isPrimaryKey) {
            indexedFields.push(field.name);
        }
    });

    if (indexedFields.length > 0) {
        code += `}, (table) => {\n  return {\n`;
        indexedFields.forEach(f => {
            code += `    ${f}Idx: index('${f}_idx').on(table.${f}),\n`;
        });
        code += `  };\n`;
    }

    code += `});\n\n`;
  });

  // Relations configuration
  tables.forEach(table => {
    const tableNameConst = `${table.name.toLowerCase()}Table`;
    const outgoingRels = relationships.filter(r => r.toTableId === table.id);
    const incomingRels = relationships.filter(r => r.fromTableId === table.id);

    if (outgoingRels.length > 0 || incomingRels.length > 0) {
      code += `export const ${table.name.toLowerCase()}Relations = relations(${tableNameConst}, ({ one, many }) => ({\n`;

      outgoingRels.forEach(rel => {
        const parentTable = tables.find(t => t.id === rel.fromTableId);
        const fkField = table.fields.find(f => f.id === rel.toFieldId);
        const parentField = parentTable?.fields.find(f => f.id === rel.fromFieldId);

        if (parentTable && fkField && parentField) {
          const parentConst = `${parentTable.name.toLowerCase()}Table`;
          code += `  ${parentTable.name.toLowerCase()}: one(${parentConst}, {\n`;
          code += `    fields: [${tableNameConst}.${fkField.name}],\n`;
          code += `    references: [${parentConst}.${parentField.name}],\n`;
          code += `  }),\n`;
        }
      });

      incomingRels.forEach(rel => {
        const childTable = tables.find(t => t.id === rel.toTableId);
        if (childTable) {
          const childConst = `${childTable.name.toLowerCase()}Table`;
          code += `  ${childTable.name.toLowerCase()}s: many(${childConst}),\n`;
        }
      });

      code += `}));\n\n`;
    }
  });

  return code;
};

// 3. TypeORM Entity Generator
export const generateTypeOrmEntities = (tables: Table[], rawRelationships: Relationship[], config: BackendConfig): VirtualFile[] => {
  const relationships = rawRelationships.filter((rel, index, self) =>
    index === self.findIndex((r) =>
      r.fromTableId === rel.fromTableId &&
      r.fromFieldId === rel.fromFieldId &&
      r.toTableId === rel.toTableId &&
      r.toFieldId === rel.toFieldId
    )
  );

  const root = `Backend/${config.projectName}/database/orm/typeorm`;
  const files: VirtualFile[] = [];

  tables.forEach(table => {
    const className = toPascalCase(table.name);
    let code = `import { Entity, PrimaryGeneratedColumn, PrimaryColumn, Column, ManyToOne, OneToMany, JoinColumn } from 'typeorm';\n`;

    // Gather unique imports of other entities referenced
    const referencedEntities = new Set<string>();
    relationships.forEach(rel => {
      if (rel.toTableId === table.id) {
        const parentTable = tables.find(t => t.id === rel.fromTableId);
        if (parentTable) referencedEntities.add(toPascalCase(parentTable.name));
      }
      if (rel.fromTableId === table.id) {
        const childTable = tables.find(t => t.id === rel.toTableId);
        if (childTable) referencedEntities.add(toPascalCase(childTable.name));
      }
    });

    referencedEntities.forEach(ent => {
      if (ent !== className) {
        code += `import { ${ent} } from './${ent}';\n`;
      }
    });

    code += `\n@Entity('${table.name.toLowerCase()}')\n`;
    code += `export class ${className} {\n\n`;

    // Fields
    table.fields.forEach(field => {
      const fTypeUpper = (field.type || 'VARCHAR').toUpperCase();
      let tsType = 'string';
      let typeDecoratorOpts = '';

      if (fTypeUpper.includes('INT')) {
        tsType = 'number';
        typeDecoratorOpts = `type: 'int'`;
      } else if (fTypeUpper === 'BOOLEAN' || fTypeUpper === 'BOOL') {
        tsType = 'boolean';
        typeDecoratorOpts = `type: 'boolean'`;
      } else if (fTypeUpper.includes('DATE') || fTypeUpper.includes('TIME')) {
        tsType = 'Date';
        typeDecoratorOpts = `type: 'timestamp'`;
      } else if (fTypeUpper.includes('DECIMAL') || fTypeUpper.includes('DOUBLE') || fTypeUpper.includes('FLOAT') || fTypeUpper.includes('NUMERIC')) {
        tsType = 'number';
        typeDecoratorOpts = `type: 'decimal'`;
      } else {
        tsType = 'string';
        typeDecoratorOpts = `type: 'varchar', length: ${field.length || 255}`;
      }

      if (field.isPrimaryKey) {
        if (field.isAutoIncrement) {
          code += `  @PrimaryGeneratedColumn()\n`;
        } else {
          code += `  @PrimaryColumn()\n`;
        }
      } else {
        let decoratorParams = `{ ${typeDecoratorOpts}`;
        if (field.allowNull) decoratorParams += `, nullable: true`;
        if (field.defaultValue !== undefined && field.defaultValue !== '') {
          const defVal = field.defaultValue;
          if (!isNaN(Number(defVal))) {
            decoratorParams += `, default: ${defVal}`;
          } else if (defVal === 'true' || defVal === 'false') {
            decoratorParams += `, default: ${defVal}`;
          } else {
            decoratorParams += `, default: '${defVal.replace(/'/g, "\\'")}'`;
          }
        }
        decoratorParams += ` }`;
        code += `  @Column(${decoratorParams})\n`;
      }

      code += `  ${field.name}${field.allowNull && !field.isPrimaryKey ? '?' : ''}: ${tsType};\n\n`;
    });

    // Relationships (outgoing FKs)
    relationships.forEach(rel => {
      if (rel.toTableId === table.id) {
        const parentTable = tables.find(t => t.id === rel.fromTableId);
        const fkField = table.fields.find(f => f.id === rel.toFieldId);
        const parentField = parentTable?.fields.find(f => f.id === rel.fromFieldId);

        if (parentTable && fkField && parentField) {
          const parentClass = toPascalCase(parentTable.name);
          const propName = parentTable.name.toLowerCase();
          
          let cascadeOpts = '';
          if (rel.onDelete && rel.onDelete !== 'NO ACTION') {
            cascadeOpts += `, { onDelete: '${rel.onDelete}' }`;
          }

          code += `  @ManyToOne(() => ${parentClass}, parent => parent.${table.name.toLowerCase()}s${cascadeOpts})\n`;
          code += `  @JoinColumn({ name: '${fkField.name}', referencedColumnName: '${parentField.name}' })\n`;
          code += `  ${propName}: ${parentClass};\n\n`;
        }
      }
    });

    // Relationships (incoming OneToMany backrefs)
    relationships.forEach(rel => {
      if (rel.fromTableId === table.id) {
        const childTable = tables.find(t => t.id === rel.toTableId);
        if (childTable) {
          const childClass = toPascalCase(childTable.name);
          const propNameList = childTable.name.toLowerCase() + 's';
          code += `  @OneToMany(() => ${childClass}, child => child.${table.name.toLowerCase()})\n`;
          code += `  ${propNameList}: ${childClass}[];\n\n`;
        }
      }
    });

    code += `}\n`;

    files.push({
      name: `${className}.ts`,
      path: `${root}/${className}.ts`,
      content: code,
      language: 'typescript'
    });
  });

  return files;
};
